#!/usr/bin/env python3
"""
Generate supabase/seeds/datum_v1.sql from the computed model.

WHY THE SEED IS TWELVE NUMBERS AND A JOIN, NOT 1,843 LITERAL ROWS

Datum V1 is a ridge on round alone, so every entry in a round shares one
expected score. Writing 1,843 INSERT rows would be 1,843 chances for a
transcription error and unreadable by eye. Instead the seed carries the
twelve fitted effects and lets the database do the join: each datum row's
heat_entry_id, heat_id, round_id, surfer_id, venue_id and field_size come
from v2's own rows, not from anything this script typed.

That is also what makes item 7 hold. The seed cannot invent a surfer-heat
that does not exist, because it never names one.

INPUT   data/datum_round_effects_v1.csv, data/datum_run_v1.json
        -- both written by scripts/compute_datum.py, and only on a PASS.
OUTPUT  supabase/seeds/datum_v1.sql
"""
import csv, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
EFF = os.path.join(ROOT, 'data', 'datum_round_effects_v1.csv')
RUN = os.path.join(ROOT, 'data', 'datum_run_v1.json')
OUT = os.path.join(ROOT, 'supabase', 'seeds', 'datum_v1.sql')


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def main():
    for f in (EFF, RUN):
        if not os.path.exists(f):
            sys.exit(f"missing {f} — run scripts/compute_datum.py first. "
                     "It writes these only when the acceptance test passes.")
    m = json.load(open(RUN))
    eff = list(csv.DictReader(open(EFF)))

    n_eff = sum(int(r['n_entries']) for r in eff)
    if n_eff != m['n_entries']:
        sys.exit(f"CONTROL FAILED — effect rows cover {n_eff} entries, "
                 f"run claims {m['n_entries']}.")

    vals = ",\n         ".join(
        f"({q(r['round_name'])}, {r['expected_score']}, {r['n_entries']}, "
        f"{str(r['on_ladder']).lower()})" for r in eff)

    sql = f"""-- =====================================================================
-- datum_v1.sql — M2 item 1. Generated by scripts/generate_datum_seed.py
-- from data/datum_round_effects_v1.csv and data/datum_run_v1.json.
-- DO NOT HAND-EDIT: regenerate instead, so the seed cannot drift from the
-- model that produced it.
--
-- Requires migration 00000000000014_datum_v1.sql.
--
-- Datum V1 is a ridge on ROUND ALONE (decision 26). It cleared the
-- acceptance test as amended by Taryn on 28 August 2026:
--
--   PRIMARY   leave-one-event-out  {m['rmse_loeo']:.4f} vs intercept-only {m['rmse_intercept_loeo']:.4f}   PASS
--   SECONDARY leave-one-season-out {m['rmse_loso']:.4f} vs intercept-only {m['rmse_intercept_loso']:.4f}   PASS
--   MONOTONE  eight-round CT ladder rises Opening -> Final              PASS
--
--   R2 vs intercept-only: {m['r2_vs_intercept']:.4f}, over {m['n_entries']} entries in {m['n_events']} events.
--
-- The three gates are CHECK constraints on datum_model_runs, so a model
-- that failed one could not be inserted by this file at all.
--
-- The 1,843 datum rows are NOT written literally. Twelve fitted effects
-- are inserted and joined to v2's own heat_entries, so every id on every
-- datum row comes from the database rather than from this file.
-- =====================================================================

BEGIN;

WITH run AS (
  INSERT INTO datum_model_runs (
    computed_on, spec, lambda, n_entries, n_events, n_rounds,
    rmse_loeo, rmse_intercept_loeo, r2_vs_intercept,
    rmse_loso, rmse_intercept_loso, ladder_monotone,
    cells_file, script)
  VALUES (
    {q(m['computed_on'])}, {q(m['spec'])}, {m['lam']}, {m['n_entries']}, {m['n_events']}, {m['n_rounds']},
    {m['rmse_loeo']}, {m['rmse_intercept_loeo']}, {m['r2_vs_intercept']},
    {m['rmse_loso']}, {m['rmse_intercept_loso']}, {str(m['ladder_monotone']).lower()},
    {q(m['cells_file'])}, {q(m['script'])})
  RETURNING id
),
eff AS (
  INSERT INTO datum_round_effects
    (model_run_id, round_name, expected_score, n_entries, on_ladder)
  SELECT run.id, v.round_name, v.expected_score, v.n_entries, v.on_ladder
  FROM run,
       (VALUES {vals}
       ) AS v(round_name, expected_score, n_entries, on_ladder)
  RETURNING model_run_id, round_name, expected_score
)
INSERT INTO datum (
  model_run_id, heat_entry_id, heat_id, round_id, surfer_id,
  expected_score, actual_heat_total, residual, venue_id, field_size)
SELECT eff.model_run_id,
       he.id,
       h.id,
       r.id,
       he.surfer_id,
       eff.expected_score,
       he.heat_total::numeric(7,4),
       (he.heat_total::numeric(7,4) - eff.expected_score)::numeric(7,4),
       h.venue_id,
       e.field_size
FROM heat_entries he
  JOIN heats  h   ON h.id = he.heat_id
  JOIN rounds r   ON r.id = h.round_id
  JOIN events e   ON e.id = r.event_id
  JOIN eff        ON eff.round_name = r.name
WHERE he.heat_total IS NOT NULL;

COMMIT;

-- ---------------------------------------------------------------------
-- VERIFY — run after applying. Every line must read as stated.
-- ---------------------------------------------------------------------
-- select * from v_datum_coverage;
--     claimed_entries {m['n_entries']} = stored_rows {m['n_entries']} = eligible_entries {m['n_entries']}
-- select count(*) from v_datum_provenance_gaps;      -- expect 0
-- select count(*) from v_datum_effect_disagreements; -- expect 0
-- select round_name, expected_score, n_entries from datum_round_effects
--   where on_ladder order by expected_score;         -- expect 8 rows, rising
"""
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w').write(sql)
    print(f"wrote {os.path.relpath(OUT, ROOT)} — {len(eff)} effects "
          f"covering {n_eff} entries")


if __name__ == '__main__':
    main()
