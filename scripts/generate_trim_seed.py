#!/usr/bin/env python3
"""
Generate supabase/seeds/trim_v1.sql from data/trim_run_v1.json.

WHY THE SEED IS ONE RUN ROW AND A RECURSION, NOT 1,843 LITERAL ROWS

Trim is a recursion, so unlike Datum it cannot be reduced to twelve
numbers and a join. But it does not need to be transcribed either: the
recursion is expressible as a recursive CTE, so the database walks its
own datum rows in its own order and computes every value itself. This
file names one alpha, one prior and one ordering. It never names a
surfer, a heat or a Trim value.

That is what keeps item 7 true for Trim as well as Datum: the seed
cannot invent a surfer-heat, because it never mentions one.

WHY THERE IS NO CELLS CSV, UNLIKE DATUM

compute_datum.py reads a retained cell aggregate because the ridge needs
numpy and could not otherwise be re-run offline. Trim's selection is pure
SQL, so its harness is SQL: supabase/checks/trim_v1_selection.sql, which
re-derives every figure in this file against v2 directly. A CSV would be
a second copy that can drift; the query cannot.

INPUT   data/trim_run_v1.json  -- the 31 August walk-forward measurement
OUTPUT  supabase/seeds/trim_v1.sql
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, '..')
RUN = os.path.join(ROOT, 'data', 'trim_run_v1.json')
OUT = os.path.join(ROOT, 'supabase', 'seeds', 'trim_v1.sql')

TEMPLATE = r"""-- =====================================================================
-- trim_v1.sql -- M2 items 2 and 3. Generated by
-- scripts/generate_trim_seed.py from data/trim_run_v1.json.
-- DO NOT HAND-EDIT: regenerate instead, so the seed cannot drift from
-- the measurement that produced it.
--
-- Requires migration 00000000000015_trim_v1.sql, and the Datum V1 run
-- (computed_on @@DATUM_ON@@, spec '@@DATUM_SPEC@@') already loaded.
--
-- Trim V1: an exponentially-weighted mean of a surfer's deviation from
-- Datum, half-life @@HL@@ heats, prior @@PRIOR@@, walked in career order.
--
--   WALK-FORWARD  Trim before each heat predicts that heat's residual
--                 better than predicting zero:
--                   Trim              RMSE @@RMSE_WF@@
--                   predict zero      RMSE @@RMSE_ZERO@@     over @@N_SCORED@@ entries
--
--   AND THE PART THAT DOES NOT FLATTER IT -- the same prediction from an
--   UNDECAYED mean of prior residuals, shrunk toward zero by a prior
--   count of 12, scores @@RMSE_FLAT@@. Paired over the same @@N_SCORED@@ entries
--   the difference is t = @@T_STAT@@. On two seasons the decay cannot be
--   shown to earn its place; almost all of Trim's skill is the prior.
--   PROJECT_PLAN.md specifies EWMA, so EWMA is what is built. The
--   measurement is recorded rather than absorbed.
--
-- The single CHECK gate on trim_model_runs is "beats predicting zero".
-- It is deliberately not "beats the shrunk flat mean", because Trim does
-- not, and writing a gate the model cannot pass is the error decision 27
-- made on 27 August and had to unpick on 28 August.
--
-- The @@N_ENTRIES@@ trim rows are NOT written literally. This file supplies
-- alpha, the prior and the ordering; the recursive CTE below walks v2's
-- own datum rows and computes every value in the database.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. The run. Bound to the Datum run whose residuals it accumulates:
--    re-fitting Datum changes every Trim value downstream, so the link
--    is a foreign key rather than a note.
-- ---------------------------------------------------------------------

INSERT INTO trim_model_runs (
  computed_on, spec, datum_model_run_id, half_life_heats, alpha, prior,
  n_entries, n_surfers, n_scored,
  rmse_walkforward, rmse_predict_zero, rmse_shrunk_flat_mean,
  paired_t_vs_shrunk, ordering, selection_file)
SELECT @@ON@@, @@SPEC@@, dmr.id, @@HL@@, @@ALPHA@@, @@PRIOR@@,
       @@N_ENTRIES@@, @@N_SURFERS@@, @@N_SCORED@@,
       @@RMSE_WF@@, @@RMSE_ZERO@@, @@RMSE_FLAT@@,
       @@T_STAT@@, @@ORDERING@@, @@SELFILE@@
FROM datum_model_runs dmr
WHERE dmr.computed_on = @@DATUM_ON@@ AND dmr.spec = @@DATUM_SPEC@@;

-- ---------------------------------------------------------------------
-- 2. The recursion.
--
--    ord    puts every datum row in its surfer's career order. The order
--           is (season_year, event_number, round_order, heat_number).
--           Corroborated 31 August 2026: event_number agrees with
--           start_date on 22 of 22 events, round_order agrees with the
--           competitive ladder on all 138 rounds, and no surfer appears
--           twice in one round, so the key is total per surfer.
--
--    chain  walks it. seq 1 starts from the run's prior; every later row
--           takes the previous row's trim_after as its trim_before, so
--           the stored chain is continuous by construction rather than
--           by assertion. v_trim_recursion_breaks audits it anyway.
--
--    The ::numeric casts in the first branch are load-bearing, not tidiness:
--    trim_model_runs.prior is numeric(7,4) and alpha is numeric(14,12),
--    while the recursive branch produces unconstrained numeric, and
--    PostgreSQL rejects a recursive CTE whose two branches disagree on a
--    column type. Found 31 August 2026 by running the seed against a
--    throwaway database; it parses and reads correctly without them.
--
--    Arithmetic is carried unrounded through the recursion and rounded
--    once on insert, so trim_before and the previous trim_after round
--    from the same value and agree exactly.
-- ---------------------------------------------------------------------

WITH RECURSIVE run AS (
  SELECT id, alpha, prior FROM trim_model_runs
  WHERE computed_on = @@ON@@ AND spec = @@SPEC@@
),
ord AS (
  SELECT d.id            AS datum_id,
         d.heat_entry_id,
         d.heat_id,
         d.surfer_id,
         d.residual,
         e.season_year,
         e.event_number,
         rd.round_order,
         h.heat_number,
         row_number() OVER (PARTITION BY d.surfer_id
                            ORDER BY e.season_year, e.event_number,
                                     rd.round_order, h.heat_number) AS seq
  FROM datum d
  JOIN datum_model_runs dmr ON dmr.id = d.model_run_id
  JOIN heats  h  ON h.id  = d.heat_id
  JOIN rounds rd ON rd.id = h.round_id
  JOIN events e  ON e.id  = rd.event_id
  WHERE dmr.computed_on = @@DATUM_ON@@ AND dmr.spec = @@DATUM_SPEC@@
),
chain AS (
  SELECT o.datum_id, o.heat_entry_id, o.heat_id, o.surfer_id, o.residual,
         o.season_year, o.event_number, o.round_order, o.heat_number, o.seq,
         run.id                AS model_run_id,
         run.alpha::numeric    AS alpha,
         run.prior::numeric    AS trim_before,
         (run.alpha * o.residual + (1 - run.alpha) * run.prior)::numeric AS trim_after,
         (1 - run.alpha)::numeric AS prior_weight
  FROM ord o CROSS JOIN run
  WHERE o.seq = 1

  UNION ALL

  SELECT o.datum_id, o.heat_entry_id, o.heat_id, o.surfer_id, o.residual,
         o.season_year, o.event_number, o.round_order, o.heat_number, o.seq,
         c.model_run_id,
         c.alpha,
         c.trim_after,
         c.alpha * o.residual + (1 - c.alpha) * c.trim_after,
         c.prior_weight * (1 - c.alpha)
  FROM chain c
  JOIN ord o ON o.surfer_id = c.surfer_id AND o.seq = c.seq + 1
)
INSERT INTO trim (
  model_run_id, surfer_id, heat_id, heat_entry_id, datum_id, seq,
  season_year, event_number, round_order, heat_number,
  residual, trim_before, trim_after, prior_weight)
SELECT model_run_id, surfer_id, heat_id, heat_entry_id, datum_id, seq,
       season_year, event_number, round_order, heat_number,
       residual::numeric(9,6),
       trim_before::numeric(9,6),
       trim_after::numeric(9,6),
       prior_weight::numeric(9,8)
FROM chain;

COMMIT;

-- ---------------------------------------------------------------------
-- VERIFY -- run after applying. Every line must read as stated.
-- ---------------------------------------------------------------------
-- select * from v_trim_coverage;
--     claimed_entries @@N_ENTRIES@@ = stored_rows @@N_ENTRIES@@ = datum_rows @@N_ENTRIES@@,
--     entries_with_no_total 9   (@@N_ENTRIES@@ + 9 = 1852, the whole of heat_entries)
-- select count(*) from v_trim_provenance_gaps;     -- expect 0
-- select count(*) from v_trim_recursion_breaks;    -- expect 0
-- select count(*) from v_trim_step_disagreements;  -- expect 0
-- select count(*) from trim;                       -- expect @@N_ENTRIES@@
-- select count(distinct surfer_id) from trim;      -- expect @@N_SURFERS@@
-- select count(*) from v_trim_current;             -- expect @@N_SURFERS@@
-- update trim set trim_after = 0 where id = 1;     -- MUST raise: append-only
--
-- The ranked table, item 6's outcome:
-- select full_name, round(trim,3) trim, n_heats, round(prior_weight,3) prior
--   from v_trim_current where n_heats >= 16 order by trim desc;
"""


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def main():
    if not os.path.exists(RUN):
        sys.exit("missing data/trim_run_v1.json")
    m = json.load(open(RUN))

    if not (m['rmse_walkforward'] < m['rmse_predict_zero']):
        sys.exit("CONTROL FAILED - Trim does not beat predicting zero; "
                 "trim_model_runs would reject this run. Nothing written.")
    if m['n_scored'] >= m['n_entries']:
        sys.exit("CONTROL FAILED - n_scored must be below n_entries: every "
                 "surfer's first heat has no prior heat to be scored on.")

    sub = {
        '@@ON@@': q(m['computed_on']),
        '@@SPEC@@': q(m['spec']),
        '@@DATUM_ON@@': q(m['datum_run_computed_on']),
        '@@DATUM_SPEC@@': q(m['datum_run_spec']),
        '@@HL@@': str(m['half_life_heats']),
        '@@ALPHA@@': str(m['alpha']),
        '@@PRIOR@@': str(m['prior']),
        '@@N_ENTRIES@@': str(m['n_entries']),
        '@@N_SURFERS@@': str(m['n_surfers']),
        '@@N_SCORED@@': str(m['n_scored']),
        '@@RMSE_WF@@': str(m['rmse_walkforward']),
        '@@RMSE_ZERO@@': str(m['rmse_predict_zero']),
        '@@RMSE_FLAT@@': str(m['rmse_shrunk_flat_mean']),
        '@@T_STAT@@': str(m['paired_t_vs_shrunk']),
        '@@ORDERING@@': q(m['ordering']),
        '@@SELFILE@@': q(m['selection_file']),
    }
    sql = TEMPLATE
    for k, v in sub.items():
        sql = sql.replace(k, v)
    if '@@' in sql:
        sys.exit("CONTROL FAILED - unsubstituted placeholder left in the seed.")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w').write(sql)
    print("wrote %s - half-life %s, alpha %s, %s entries over %s surfers"
          % (os.path.relpath(OUT, ROOT), m['half_life_heats'], m['alpha'],
             m['n_entries'], m['n_surfers']))


if __name__ == '__main__':
    main()
